namespace FishAndChill.Gear
{
    /// <summary>Les grandes familles de leurres et d'appâts, comme dans la vraie pêche.</summary>
    public enum LureType
    {
        /// <summary>Appâts naturels : ver, asticots, crevette, lanière de calmar.</summary>
        Natural,

        /// <summary>Cuillères tournantes (palette qui tourne autour d'un axe).</summary>
        Spinner,

        /// <summary>Cuillères ondulantes (Toby, Crocodile, Devon).</summary>
        Spoon,

        /// <summary>Poissons nageurs à bavette (minnow, jerkbait, crankbait).</summary>
        Minnow,

        /// <summary>Leurres souples (shad, finesse, grub).</summary>
        SoftBait,

        /// <summary>Leurres de surface (popper, stickbait, walking-the-dog).</summary>
        Surface,

        /// <summary>Jigs métalliques (pilker, casting jig, slow jig).</summary>
        Jig,

        /// <summary>Turluttes à calmar (egi, phosphorescente).</summary>
        SquidJig,

        /// <summary>Leurres de traîne au large (jupe octopus, plume).</summary>
        Troll,

        /// <summary>Mouches (sèche, noyée, streamer).</summary>
        Fly,
    }
}
